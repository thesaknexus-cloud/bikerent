-- Add after the existing users and bikes tables. Spring/JPA can create this
-- table automatically for local H2; this migration is also suitable for PostgreSQL.
CREATE TABLE rental_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bike_id BIGINT NOT NULL REFERENCES bikes(id),
    owner_id BIGINT NOT NULL REFERENCES users(id),
    renter_id BIGINT REFERENCES users(id),
    renter_email VARCHAR(255) NOT NULL,
    renter_name VARCHAR(255),
    renter_phone VARCHAR(255),
    invitation_code VARCHAR(36) NOT NULL UNIQUE,
    agreed_duration_minutes INTEGER NOT NULL CHECK (agreed_duration_minutes BETWEEN 1 AND 43200),
    fine_rate_paise_per_minute BIGINT NOT NULL DEFAULT 250 CHECK (fine_rate_paise_per_minute >= 0),
    status VARCHAR(20) NOT NULL CHECK (status IN ('SCHEDULED', 'ACTIVE', 'COMPLETED')),
    start_time TIMESTAMP WITH TIME ZONE,
    expected_return_time TIMESTAMP WITH TIME ZONE,
    end_time TIMESTAMP WITH TIME ZONE,
    final_late_seconds BIGINT,
    final_fine_paise BIGINT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK ((status = 'SCHEDULED' AND start_time IS NULL AND end_time IS NULL) OR
           (status = 'ACTIVE' AND start_time IS NOT NULL AND expected_return_time IS NOT NULL AND end_time IS NULL) OR
           (status = 'COMPLETED' AND start_time IS NOT NULL AND expected_return_time IS NOT NULL AND end_time IS NOT NULL AND final_fine_paise IS NOT NULL))
);
CREATE INDEX idx_rental_owner_created ON rental_sessions(owner_id, created_at);
CREATE INDEX idx_rental_renter_created ON rental_sessions(renter_id, created_at);
CREATE INDEX idx_rental_bike_status ON rental_sessions(bike_id, status);
